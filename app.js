function buildCode(family, suffix) {
  let v = suffix.trim().toUpperCase().replace(/^-+/, "");
  if (!v) return "";
  if (/^\d+$/.test(v)) v = v.padStart(4, "0");
  return `${family}-${v}`;
}

function normalizeCode(raw) {
  let v = raw.trim().toUpperCase();
  if (!v) return "";
  const known = FAMILIES.find((f) => v.startsWith(f.id));
  if (known) {
    let rest = v.slice(known.id.length).replace(/^-+/, "");
    if (/^\d+$/.test(rest)) rest = rest.padStart(4, "0");
    return `${known.id}-${rest}`;
  }
  return v;
}

// --- Almacenamiento compartido via Firebase Firestore ---
// Reemplaza el window.storage propio de los artifacts de Claude.
// Cada "key" es un documento dentro de la coleccion "localizador".
const db = firebase.firestore();

async function storageGet(key) {
  try {
    const snap = await db.collection("localizador").doc(key).get();
    if (!snap.exists) return null;
    return { value: snap.data().value };
  } catch (e) {
    console.error("storageGet error", key, e);
    return null;
  }
}

async function storageSet(key, value) {
  try {
    await db.collection("localizador").doc(key).set({
      value,
      updatedAt: firebase.firestore.FieldValue.serverTimestamp(),
    });
    return { value };
  } catch (e) {
    console.error("storageSet error", key, e);
    return null;
  }
}

